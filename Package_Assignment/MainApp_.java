package Package_Assignment;
import static java.lang.Math.*;

public class MainApp_ {

    public static void main(String[] args) {

        System.out.println("Square Root of 25: " + sqrt(25));
        System.out.println("Power 2^3: " + pow(2,3));
        System.out.println("Maximum of 10 and 20: " + max(10,20));
        System.out.println("Minimum of 5 and 8: " + min(5,8));
        System.out.println("Absolute value of -9: " + abs(-9));

    }

}